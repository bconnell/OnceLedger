#!/usr/bin/env sh
set -eu
cd "$(dirname "$0")/.."
# Check public-facing prose and source comments without depending on an external linter.
files='README.md docs/architecture.md pom.xml src/main/resources/static/index.html'
for file in $files; do
  test -s "$file" || { printf 'Missing public text: %s\n' "$file" >&2; exit 1; }
done
if grep -nEi 'lorem ipsum|as an ai|generated by (an )?ai|\b(todo|fixme|tbd)\b|C:\\Users\\|/Users/[^ /]+/|github actions outage' $files; then
  printf '%s\n' 'Public-facing documentation contains unfinished or private text.' >&2
  exit 1
fi
# Source code and migration text are checked for the same unsafe publication markers.
if find src -type f \( -name '*.java' -o -name '*.sql' \) -exec grep -nEi \
  'lorem ipsum|as an ai|generated by (an )?ai|\b(todo|fixme|tbd)\b|C:\\Users\\|/Users/[^ /]+/|github actions outage' {} +; then
  printf '%s\n' 'Source contains unfinished or private text.' >&2
  exit 1
fi
# Review of factual claims, provenance, and privacy remains a human gate.
printf '%s\n' 'Public-text pattern and required-file checks passed.'
