$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repository = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$files = @('README.md', 'docs/architecture.md', 'pom.xml', 'src/main/resources/static/index.html')
$pattern = 'lorem ipsum|as an ai|generated by (an )?ai|\b(todo|fixme|tbd)\b|C:\\Users\\|/Users/[^ /]+/|internal development constraint'
foreach ($name in $files) {
    $path = Join-Path $repository $name
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Required public text is missing: $name" }
    $content = [System.IO.File]::ReadAllText($path)
    if ([string]::IsNullOrWhiteSpace($content)) { throw "Public text is empty: $name" }
    if ($content -match $pattern) { throw "Unfinished or private text detected in: $name" }
}
$sourceRoot = Join-Path $repository 'src'
Get-ChildItem -LiteralPath $sourceRoot -Recurse -File | Where-Object {
    $_.Extension -eq '.java' -or $_.Extension -eq '.sql'
} | ForEach-Object {
    $content = [System.IO.File]::ReadAllText($_.FullName)
    if ($content -match $pattern) { throw "Unfinished or private text detected in: $($_.FullName)" }
}
Write-Host 'Public-text pattern and required-file checks passed.' 
