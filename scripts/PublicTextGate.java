import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.concurrent.TimeUnit;
import java.util.regex.Pattern;

/**
 * Checks repository text for unfinished prose and likely accidental disclosures.
 * This is a pattern gate, not a substitute for reviewing factual claims.
 */
public final class PublicTextGate {
    private static final List<String> REQUIRED = List.of(
            "README.md",
            "LICENSE",
            "docs/architecture.md",
            "docs/verification.md",
            "pom.xml",
            "compose.yaml",
            "src/main/resources/static/index.html");
    private static final Set<String> EXTENSIONS = Set.of(
            ".md", ".java", ".sql", ".html", ".xml", ".yml", ".yaml", ".json",
            ".ps1", ".sh", ".properties", ".css", ".js", ".txt");
    private static final List<Pattern> DISALLOWED = List.of(
            Pattern.compile("(?i)\\b(lorem ipsum|as an ai|generated by (an )?ai|todo|fixme|tbd)\\b"),
            Pattern.compile("(?i)([a-z]:\\\\users\\\\|/users/|/home/[^/\\s]+/)"),
            Pattern.compile("-----BEGIN [A-Z ]*PRIVATE KEY-----"),
            Pattern.compile("\\bghp_[A-Za-z0-9]{20,}\\b"),
            Pattern.compile("\\bsk-proj-[A-Za-z0-9_-]{16,}\\b"));

    private PublicTextGate() {
    }

    public static void main(String[] args) throws Exception {
        Path root = Path.of("").toAbsolutePath().normalize();
        for (String required : REQUIRED) {
            Path file = root.resolve(required);
            if (!Files.isRegularFile(file) || Files.size(file) == 0) {
                throw new IllegalStateException("Missing or empty required file: " + required);
            }
        }

        Process process = new ProcessBuilder(
                "git", "ls-files", "-z", "--cached", "--others", "--exclude-standard")
                .directory(root.toFile())
                .redirectErrorStream(true)
                .start();
        byte[] output = process.getInputStream().readAllBytes();
        if (!process.waitFor(10, TimeUnit.SECONDS)) {
            process.destroyForcibly();
            throw new IllegalStateException("Git file listing timed out.");
        }
        if (process.exitValue() != 0) {
            throw new IllegalStateException("Git file listing failed.");
        }

        String entries = new String(output, StandardCharsets.UTF_8);
        int scanned = 0;
        int start = 0;
        for (int index = 0; index <= entries.length(); index++) {
            if (index == entries.length() || entries.charAt(index) == '\0') {
                if (index > start) {
                    String name = entries.substring(start, index);
                    // Exclude this scanner: its own source contains the rejected patterns.
                    if (!name.equals("scripts/PublicTextGate.java") && shouldScan(name)) {
                        Path file = root.resolve(name).normalize();
                        if (!file.startsWith(root)) {
                            throw new IllegalStateException("File escapes the repository: " + name);
                        }
                        if (Files.isRegularFile(file)) {
                            scan(name, Files.readString(file, StandardCharsets.UTF_8));
                            scanned++;
                        }
                    }
                }
                start = index + 1;
            }
        }
        if (scanned < REQUIRED.size()) {
            throw new IllegalStateException("Repository text scan was unexpectedly incomplete.");
        }
        System.out.println("Public-text pattern audit passed for " + scanned + " files.");
        System.out.println("Factual claims and provenance still require review against source and execution evidence.");
    }

    private static boolean shouldScan(String name) {
        String lower = name.toLowerCase(Locale.ROOT);
        if (lower.equals(".gitignore")) {
            return true;
        }
        for (String extension : EXTENSIONS) {
            if (lower.endsWith(extension)) {
                return true;
            }
        }
        return false;
    }

    private static void scan(String name, String content) throws IOException {
        if (content.isBlank()) {
            throw new IOException("Empty tracked text file: " + name);
        }
        for (Pattern blocked : DISALLOWED) {
            if (blocked.matcher(content).find()) {
                throw new IOException("Unfinished or sensitive text in: " + name);
            }
        }
    }
}
